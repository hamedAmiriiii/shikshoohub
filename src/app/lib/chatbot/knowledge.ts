function patternWords(patterns: string[]): string[] {
  const out: string[] = [];
  for (const p of patterns) {
    for (const w of p.split(/\s+/)) {
      if (w.length > 1) out.push(w.replace(/[؟?]/g, ""));
    }
  }
  return out;
}

