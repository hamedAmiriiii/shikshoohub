export function setShopContractRequired(required: boolean): void {
  if (typeof window === "undefined") return;
  if (required) localStorage.setItem(CONTRACT_REQUIRED_STORAGE_KEY, "1");
  else localStorage.removeItem(CONTRACT_REQUIRED_STORAGE_KEY);
}

export function isShopContractRequiredStored(): boolean {
  if (typeof window === "undefined") return false;
  return localStorage.getItem(CONTRACT_REQUIRED_STORAGE_KEY) === "1";
}

